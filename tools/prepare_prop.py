"""
Prepare a small prop generated by Meshy (a treasure chest, a covenant seal) for the game:
centre it, stand it on its base at height 0, scale its largest side to 1, shrink the texture,
and export a light GLB to public/models/.

    python tools/prepare_prop.py -- models/treasure.glb public/models/treasure.glb
    python tools/prepare_prop.py -- models/seal.glb public/models/seal.glb
"""
import bpy, sys, mathutils

argv = sys.argv[sys.argv.index('--') + 1:]
src, dst = argv[0], argv[1]
TEX = 512
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=src)
scene = bpy.context.scene
# Meshy sometimes leaves a stray helper sphere in the file: drop it.
for o in list(scene.objects):
    if o.type == 'MESH' and o.name.lower().startswith(('icosphere', 'sphere')):
        print('removed stray', o.name); bpy.data.objects.remove(o, do_unlink=True)
# A rig from Meshy is dropped: the game bends the wings itself, and a rig would fight the rescaling.
for o in list(scene.objects):
    if o.type == 'MESH':
        for m in list(o.modifiers):
            if m.type == 'ARMATURE': o.modifiers.remove(m)
        o.parent = None
        o.vertex_groups.clear()
for o in list(scene.objects):
    if o.type in ('ARMATURE', 'EMPTY'): bpy.data.objects.remove(o, do_unlink=True)
meshes = [o for o in scene.objects if o.type == 'MESH']
for o in meshes:
    o.data.transform(o.matrix_world); o.matrix_world = mathutils.Matrix.Identity(4)
vs = [v.co for o in meshes for v in o.data.vertices]
lo = mathutils.Vector([min(v[i] for v in vs) for i in range(3)])
hi = mathutils.Vector([max(v[i] for v in vs) for i in range(3)])
k = 1 / max(hi - lo)
shift = mathutils.Vector(((lo.x + hi.x) / 2, (lo.y + hi.y) / 2, lo.z))
for o in meshes:
    o.data.transform(mathutils.Matrix.Scale(k, 4) @ mathutils.Matrix.Translation(-shift))
    o.data.update()
for img in bpy.data.images:
    if max(img.size) > TEX: img.scale(TEX, TEX)
for o in scene.objects: o.select_set(True)
bpy.ops.export_scene.gltf(filepath=dst, export_format='GLB', export_image_format='JPEG', export_jpeg_quality=85, export_apply=True, use_selection=False)
tris = sum(sum(len(p.vertices) - 2 for p in o.data.polygons) for o in meshes)
print(f'wrote {dst}: {tris} triangles, size {[round(x * k, 3) for x in (hi - lo)]}')
